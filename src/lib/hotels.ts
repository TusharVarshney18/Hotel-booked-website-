export function getHotel(slug: string) {
  return hotels.find((hotel) => hotel.slug === slug);
}

export function getFeaturedHotels() {
  return hotels.filter((hotel) => hotel.featured);
}

export function getDestinations() {
  const map = new Map<
    string,
    { region: string; city: string; country: string; image: string; count: number }
  >();
  for (const hotel of hotels) {
    const current = map.get(hotel.city);
    if (current) {
      current.count += 1;
    } else {
      map.set(hotel.city, {
        region: hotel.region,
        city: hotel.city,
        country: hotel.country,
        image: hotel.images[0],
        count: 1,
      });
    }
  }
  return Array.from(map.values());
}

export function getRoom(hotel: Hotel, roomId: string) {
  return hotel.rooms.find((room) => room.id === roomId);
}
